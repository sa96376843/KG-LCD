# ---------------------------------------------------------- wilcoxon
def tab_wilcoxon():
    from scipy.stats import wilcoxon
    d, b = load("dermamnist"), load("bloodmnist")
    methods = ["CNN", "kNN", "LabelProp", "GCN", "Louvain",
               "ACL-single"]
    # per-run proxy: per-class F1 values on both datasets (n = 15)
    from sklearn.metrics import f1_score, confusion_matrix
    import numpy as np

    def per_class_f1(ds, method):
        f = np.load(os.path.join(DATA, f"{ds}_seed0_emb.npz"))
        res = load(ds)
        # recompute predictions per method where stored
        if method == "KG-LCD":
            pred = np.load(os.path.join(
                DATA, f"{ds}_seed0_ours.npz"))["pred"]
        else:
            # approximate per-class F1 from aggregate is not possible;
            # use sign test on the 6 summary metrics instead
            return None
        return f1_score(f["test_y"], pred, average=None)

    rows = []
    for m in methods:
        vd = [d["KG-LCD"][k] - d[m][k] for k in ("acc", "f1", "auc")]
        vb = [b["KG-LCD"][k] - b[m][k] for k in ("acc", "f1", "auc")]
        diffs = np.array(vd + vb)
        stat, p = wilcoxon(diffs)
        sig = "$p<0.05$" if p < 0.05 else f"$p={p:.3f}$"
        rows.append(f"    KG-LCD vs.\\ {m} & {diffs.mean()*100:+.2f} & "
                    f"{stat:.0f} & {p:.4f} & {sig}\\\\")
    w("tab_wilcoxon.tex", r"""\begin{table}[t]
  \centering
  \caption{Wilcoxon signed-rank test of KG-LCD against each baseline
  on the pooled ACC/F1/AUC differences over both datasets ($n=6$
  paired measurements).}
  \label{tab:wilcoxon}
  \small
  \begin{tabular}{lcccc}
    \toprule
    Comparison & Mean $\Delta$ (\%) & $W$ & $p$-value & Significance\\
    \midrule
""" + "\n".join(rows) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")


