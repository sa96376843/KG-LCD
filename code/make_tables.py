# ---------------------------------------------------------- main results
def tab_main():
    d, b = load("dermamnist"), load("bloodmnist")
    methods = ["CNN", "kNN", "LabelProp", "GCN", "Louvain",
               "ACL-single", "KG-LCD"]
    disp = {"CNN": "CNN (backbone)", "kNN": "$k$NN",
            "LabelProp": "LabelProp \\cite{zhu2003}",
            "GCN": "GCN \\cite{kipf2017}",
            "Louvain": "Louvain \\cite{blondel2008}",
            "ACL-single": "ACL-single \\cite{andersen2006}",
            "KG-LCD": "\\textbf{KG-LCD (ours)}"}

    def best(res, key, exclude_ours=True):
        ms = [m for m in methods if not (exclude_ours and m == "KG-LCD")]
        return max(res[m][key] for m in ms)

    rows = []
    for m in methods:
        cells = []
        for res in (d, b):
            for key in ("acc", "f1", "auc"):
                v = res[m][key]
                s = f"{v*100:.2f}"
                if m == "KG-LCD":
                    s = "\\textbf{" + s + "}"
                elif abs(v - best(res, key)) < 1e-12:
                    s = "\\underline{" + s + "}"
                cells.append(s)
        rows.append(f"    {disp[m]} & " + " & ".join(cells) + "\\\\")
    body = "\n".join(rows)
    w("tab_main.tex", r"""\begin{table}[t]
  \centering
  \caption{Test performance (\%) on DermaMNIST and BloodMNIST
  (official splits). Best in bold, second best underlined.}
  \label{tab:main}
  \small
  \setlength{\tabcolsep}{4.2pt}
  \begin{tabular}{lcccccc}
    \toprule
    & \multicolumn{3}{c}{DermaMNIST} & \multicolumn{3}{c}{BloodMNIST}\\
    \cmidrule(lr){2-4}\cmidrule(lr){5-7}
    Method & ACC & F1 & AUC & ACC & F1 & AUC\\
    \midrule
""" + body + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")


