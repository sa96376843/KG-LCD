"""
make_tables.py
--------------
Generates all LaTeX tables (tables/*.tex) from the experimental
result JSONs. Numbers are copied verbatim from the measured results.
"""
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
TAB = os.path.join(ROOT, "tables")
os.makedirs(TAB, exist_ok=True)

HDR = "% Auto-generated by make_tables.py from measured results.\n"


def w(name, text):
    with open(os.path.join(TAB, name), "w") as fh:
        fh.write(HDR + text)
    print("saved", name)


def load(ds, seed=0):
    return json.load(open(os.path.join(DATA, f"{ds}_seed{seed}_results.json")))


